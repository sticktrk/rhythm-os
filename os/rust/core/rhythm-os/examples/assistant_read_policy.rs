//! Regenerate the admin API's fail-closed POST classification.
use rhythm_os::assistant::{operation_registry, OperationTier};
fn main() {
    if std::env::args().nth(1).as_deref() == Some("--staff-catalog") {
        println!("// Generated by cargo run -p rhythm-os --example assistant_read_policy -- --staff-catalog.");
        println!("const staffHubCatalogJson = r'''[");
        let registry = operation_registry();
        for (index, op) in registry.iter().enumerate() {
            let descriptor = serde_json::json!({
                "id": op.id, "tier": op.tier, "description": op.description,
                "input_schema": op.input_schema, "requires_owner_approval": op.requires_owner_approval,
                "observes_household": op.observes_household
            });
            let comma = if index + 1 == registry.len() { "" } else { "," };
            println!("{descriptor}{comma}");
        }
        println!("]''';");
        return;
    }
    println!("// Generated by cargo run -p rhythm-os --example assistant_read_policy.");
    let registry = operation_registry();
    for (name, mut ids) in [
        (
            "assistantReadOperations",
            registry
                .iter()
                .filter(|op| op.tier == OperationTier::Read)
                .map(|op| &op.id)
                .collect::<Vec<_>>(),
        ),
        (
            "assistantHouseholdOperations",
            registry
                .iter()
                .filter(|op| op.observes_household)
                .map(|op| &op.id)
                .collect::<Vec<_>>(),
        ),
    ] {
        ids.sort_unstable();
        println!("const {name} = <String>{{");
        for id in ids {
            println!("  '{id}',");
        }
        println!("}};");
    }
}
