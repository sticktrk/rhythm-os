//! Regenerate the admin API's fail-closed POST classification.
use rhythm_os::assistant::{operation_registry, OperationTier};
fn main() {
    println!("// Generated by cargo run -p rhythm-os --example assistant_read_policy.");
    let registry = operation_registry();
    for (name, mut ids) in [
        (
            "assistantReadOperations",
            registry
                .iter()
                .filter(|op| op.tier == OperationTier::Read)
                .map(|op| &op.id)
                .collect::<Vec<_>>(),
        ),
        (
            "assistantHouseholdOperations",
            registry
                .iter()
                .filter(|op| op.observes_household)
                .map(|op| &op.id)
                .collect::<Vec<_>>(),
        ),
    ] {
        ids.sort_unstable();
        println!("const {name} = <String>{{");
        for id in ids {
            println!("  '{id}',");
        }
        println!("}};");
    }
}
